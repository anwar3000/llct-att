class AttendanceApp extends StatelessWidget {
  const AttendanceApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Attendance Pro',
      debugShowCheckedModeBanner: false,
      theme: buildTheme(),
      home: const AuthGate(),
    );
  }
}

/// Routes to Login, the employee app, or the management dashboard.
class AuthGate extends StatelessWidget {
  const AuthGate({super.key});

  @override
  Widget build(BuildContext context) {
    return StreamBuilder<User?>(
      stream: AuthService.authChanges,
      builder: (context, snap) {
        if (snap.connectionState == ConnectionState.waiting) return const _Splash();
        final fbUser = snap.data;
        if (fbUser == null) return const LoginScreen();
        return _ProfileGate(uid: fbUser.uid, key: ValueKey(fbUser.uid));
      },
    );
  }
}

class _ProfileGate extends StatefulWidget {
  final String uid;
  const _ProfileGate({super.key, required this.uid});

  @override
  State<_ProfileGate> createState() => _ProfileGateState();
}

class _ProfileGateState extends State<_ProfileGate> {
  late final Stream<AppUser?> _stream = Db.userStream(widget.uid);

  @override
  Widget build(BuildContext context) {
    return StreamBuilder<AppUser?>(
      stream: _stream,
      builder: (context, snap) {
        if (snap.hasError) {
          return _Blocked(
            title: 'Could not load your profile',
            message: '${snap.error}',
          );
        }
        if (!snap.hasData && snap.connectionState == ConnectionState.waiting) {
          return const _Splash();
        }
        final user = snap.data;
        if (user == null) {
          return _Blocked(
            title: 'Profile not set up',
            message:
                'Your login exists but has no staff profile yet. Ask your manager to add you, '
                'or (for the first admin) create Firestore document users/<UID> with role = admin.',
            uid: widget.uid,
          );
        }
        if (!user.active) {
          TrackingService.instance.stop();
          return const _Blocked(
            title: 'Account disabled',
            message: 'Your account has been deactivated. Please contact management.',
          );
        }
        if (user.role == 'docs') {
          return const _Blocked(
            title: 'Documents Portal login',
            message: 'This login is for the LLCT Documents Portal on the web, not the attendance app. '
                'Open https://anwar3000.github.io/llct-att/portal.html in a browser.',
          );
        }
        CurrentUser.me = user;
        return user.isManagement ? AdminShell(me: user) : EmployeeShell(me: user);
      },
    );
  }
}

class _Splash extends StatelessWidget {
  const _Splash();
  @override
  Widget build(BuildContext context) => const Scaffold(
        body: Center(child: CircularProgressIndicator()),
      );
}

class _Blocked extends StatelessWidget {
  final String title;
  final String message;
  final String? uid;
  const _Blocked({required this.title, required this.message, this.uid});

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      body: SafeArea(
        child: Padding(
          padding: const EdgeInsets.all(28),
          child: Column(mainAxisAlignment: MainAxisAlignment.center, children: [
            const Icon(Icons.lock_person_outlined, size: 64, color: AppColors.muted),
            const SizedBox(height: 16),
            Text(title,
                textAlign: TextAlign.center,
                style: const TextStyle(fontSize: 20, fontWeight: FontWeight.w700)),
            const SizedBox(height: 8),
            Text(message,
                textAlign: TextAlign.center, style: const TextStyle(color: AppColors.muted)),
            if (uid != null) ...[
              const SizedBox(height: 16),
              const Text('Your UID (Firestore document ID):',
                  style: TextStyle(fontWeight: FontWeight.w600)),
              const SizedBox(height: 4),
              SelectableText(uid!,
                  textAlign: TextAlign.center,
                  style: const TextStyle(fontFamily: 'monospace', fontSize: 13)),
            ],
            const SizedBox(height: 24),
            OutlinedButton.icon(
              onPressed: AuthService.signOut,
              icon: const Icon(Icons.logout),
              label: const Text('Sign out'),
            ),
          ]),
        ),
      ),
    );
  }
}

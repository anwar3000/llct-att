"""Generate lib/firebase_options.dart from a google-services.json file.

Usage: python3 tools/gen_firebase_options.py path/to/google-services.json [package_name]

This replaces `flutterfire configure` so the APK can be built on GitHub Actions
(or any machine) with only the google-services.json downloaded from Firebase.
"""
import json
import sys

src = sys.argv[1]
package = sys.argv[2] if len(sys.argv) > 2 else "com.attendancepro.attendance_pro"

with open(src, encoding="utf-8") as f:
    data = json.load(f)

info = data["project_info"]
clients = data.get("client", [])
client = next(
    (c for c in clients
     if c.get("client_info", {}).get("android_client_info", {}).get("package_name") == package),
    None,
)
if client is None:
    found = [c.get("client_info", {}).get("android_client_info", {}).get("package_name") for c in clients]
    sys.exit(
        f"ERROR: google-services.json has no Android app with package '{package}'. "
        f"Found: {found}. In Firebase, add an Android app with package name {package}."
    )

api_key = client["api_key"][0]["current_key"]
app_id = client["client_info"]["mobilesdk_app_id"]
sender = info["project_number"]
project_id = info["project_id"]
bucket = info.get("storage_bucket", "")

out = f"""// GENERATED by tools/gen_firebase_options.py — do not edit by hand.
import 'package:firebase_core/firebase_core.dart' show FirebaseOptions;
import 'package:flutter/foundation.dart' show defaultTargetPlatform, TargetPlatform;

class DefaultFirebaseOptions {{
  static FirebaseOptions get currentPlatform {{
    if (defaultTargetPlatform == TargetPlatform.android) return android;
    throw UnsupportedError('This app is configured for Android only.');
  }}

  static const FirebaseOptions android = FirebaseOptions(
    apiKey: '{api_key}',
    appId: '{app_id}',
    messagingSenderId: '{sender}',
    projectId: '{project_id}',
    storageBucket: '{bucket}',
  );
}}
"""
with open("lib/firebase_options.dart", "w", encoding="utf-8") as f:
    f.write(out)
print(f"Wrote lib/firebase_options.dart for project '{project_id}'")
